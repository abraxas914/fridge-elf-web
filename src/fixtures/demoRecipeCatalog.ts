type CuratedRecipe = SavedRecipe & {
  category: RecipeCategory
  ingredients: readonly RecipeIngredient[]
  source: 'seed'
  steps: readonly string[]
}

interface RecipeSeedInput {
  id: string
  key: FoodKey | 'unknown'
  name: string
  cn: string
  category: RecipeCategory
  ingredients: readonly RecipeIngredient[]
  steps: readonly string[]
  tags?: readonly string[]
  time?: number
}

const ingredient = (
  name: string,
  amount?: string,
  key?: FoodKey,
): RecipeIngredient => ({
  name,
  ...(amount ? { amount } : {}),
  ...(key ? { key } : {}),
})

const seed = ({
  id,
  key,
  name,
  cn,
  category,
  ingredients,
  steps,
  tags = [],
  time = 0,
}: RecipeSeedInput): CuratedRecipe => ({
  id,
  key,
  name,
  cn,
  category,
  ingredients,
  steps,
  time,
  kcal: null,
  tags: [category, ...tags],
  match: false,
  need: ingredients.map((item) => item.key ?? item.name),
  desc: `${cn}的食材与步骤已整理，可直接查看或生成食谱插画。`,
  source: 'seed',
})

